FILLED = {"stop"}

_cache: dict = {}


def svg(name: str, color: str) -> bytes:
    paths = "".join(f'<path d="{d}"/>' for d in PATHS[name])
    paint = f'fill="{color}" stroke="none"' if name in FILLED else \
        f'fill="none" stroke="{color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" {paint}>{paths}</svg>'.encode()


def pixmap(name: str, color: str = "#ECECEC", size: int = 18) -> QPixmap:
    key = (name, color, size)
    if key not in _cache:
        scale = 3  # vẽ to rồi đặt devicePixelRatio để nét sắc trên màn hình 125–200%
        pm = QPixmap(size * scale, size * scale)
        pm.fill(Qt.GlobalColor.transparent)
        p = QPainter(pm)
        QSvgRenderer(QByteArray(svg(name, color))).render(p, QRectF(0, 0, size * scale, size * scale))
        p.end()
        pm.setDevicePixelRatio(scale)
        _cache[key] = pm
    return _cache[key]


def icon(name: str, color: str = "#ECECEC", size: int = 18) -> QIcon:
    return QIcon(pixmap(name, color, size))


