def render_png(name: str, color: str, path: str, px: int = 256) -> str:
    """Vẽ icon ra PNG trong suốt. Dùng QImage (an toàn ở luồng nền, nơi code tạo slide chạy)."""
    from PySide6.QtGui import QImage
    img = QImage(px, px, QImage.Format.Format_ARGB32)
    img.fill(0)
    p = QPainter(img)
    QSvgRenderer(QByteArray(svg(name, color))).render(p, QRectF(px * 0.04, px * 0.04, px * 0.92, px * 0.92))
    p.end()
    img.save(path)
    return path
